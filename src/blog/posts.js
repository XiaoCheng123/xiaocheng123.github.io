这就是我最想问自己的那个问题：道理都懂，为什么做不到？

我现在的答案是：这不是知识问题，是习惯问题。而且是一个有奖励的习惯。

反驳的奖励是即时的——话一出口，你赢了，你占了上风，你把自己放回了安全的位置。而听别人说完、接住他的情绪，奖励是延迟的、看不见的，还得承担“我是不是没立场”的风险。

所以我们不是不知道怎么做，我们是手上没有可以替换的动作。你知道不该熬夜，还是熬夜；你知道不该反驳，还是反驳。改说话的方式，跟改一个姿势一样，靠的是练另一个动作，不是靠再下一次决心。

还有一层：我们从小就是在被反驳里长大的。一个人如果在小饭桌上被否定过很多次，长大以后就很难不反驳——因为在他的经验里，不反驳，就等着被否定。

这不是性格问题，也不是修养问题。这是被环境训练出来的条件反射。

